// shareCheckupPath writes a checkup fixture carrying public identity
// addresses and a hostname, the fields share redaction must handle.
func shareCheckupPath(t *testing.T) string {
	t.Helper()
	rep := checkup.CheckupReport{
		ReportKind: "checkup",
		System: sysinfo.SystemInfo{OS: sysinfo.OSInfo{
			Hostname: "prod-web-01", Name: "Ubuntu 24.04", Kernel: "6.8.0",
		}},
		NetworkInfo: checkup.NetworkInfoSection{
			SectionState: checkup.SectionState{Enabled: true, Status: "ok"},
			Result: &checkup.NetworkIdentityResult{
				PublicIPv4: &checkup.PublicIPIdentity{IP: "96.9.228.37", IPVersion: "v4"},
			},
		},
	}
	data, err := json.Marshal(rep)
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(t.TempDir(), "checkup.json")
	if err := os.WriteFile(path, data, 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

