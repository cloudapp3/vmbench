func TestRunShareArgumentValidation(t *testing.T) {
	path := shareCheckupPath(t)
	notAReport := filepath.Join(t.TempDir(), "other.json")
	if err := os.WriteFile(notAReport, []byte(`{"hello":"world"}`), 0o600); err != nil {
		t.Fatal(err)
	}
	tests := []struct {
		name string
		args []string
	}{
		{name: "no report", args: []string{"share"}},
		{name: "two reports", args: []string{"share", path, path}},
		{name: "unknown format", args: []string{"share", "--format", "yaml", path}},
		{name: "unknown media", args: []string{"share", "--media", "verbose", path}},
		{name: "unknown redact", args: []string{"share", "--redact", "aggressive", path}},
		{name: "unknown provider", args: []string{"share", "--provider", "bogus", path}},
		{name: "custom without endpoint", args: []string{"share", "--provider", "custom", path}},
		{name: "not a report", args: []string{"share", notAReport}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if code := run(tt.args); code != 2 {
				t.Fatalf("share %v exit = %d, want 2", tt.args, code)
			}
		})
	}
}

