func TestRunShareDryRunTouchesNoNetwork(t *testing.T) {
	var hits int
	srv := httptest.NewTLSServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		hits++
	}))
	defer srv.Close()
	path := shareCheckupPath(t)

	output, code := captureStdout(t, func() int {
		return run([]string{"share", "--dry-run", "--provider", "custom", "--share-endpoint", srv.URL, path})
	})
	if code != 0 {
		t.Fatalf("share --dry-run exit = %d", code)
	}
	if hits != 0 {
		t.Fatalf("dry-run performed %d network requests, want 0", hits)
	}
	if !strings.Contains(output, "203.0.113.1") {
		t.Fatalf("dry-run payload lacks the placeholder address:\n%s", output)
	}
	if strings.Contains(output, "96.9.228.37") {
		t.Fatalf("dry-run payload leaked the public address:\n%s", output)
	}
	if !strings.Contains(output, "generated by") {
		t.Fatalf("dry-run payload lacks the footer:\n%s", output)
	}
}

